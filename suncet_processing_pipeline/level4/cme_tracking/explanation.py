"""Static, numbered visual explanation of the Level 4 CME method.

The figures written here are diagnostic teaching products, not additional
science products.  Science-space arrays are regenerated by the same polar and
likelihood functions used by :func:`run_known_window`; intensity stretches are
applied only while rendering and are labeled as display-only in every panel
where they occur.
"""


@dataclass(frozen=True)
class CMEExplanationArtifacts:
    """Paths and representative coordinates for one method explanation."""

    frame_index: int
    frame_number: int
    representative_position_angle_deg: float
    panel_paths: tuple[Path, ...]
    overview_path: Path


